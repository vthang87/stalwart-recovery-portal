const PREFERRED = ["en-US", "vi-VN"];

export function isStalwartLocale(value: string) {
  return STALWART_LOCALES.some((item) => item.value === value);
}

export function localeOptionText(item: { value: string; label: string }) {
  const name = item.label.replace(/\.$/, "").split(/ language| locale/i)[0]?.trim();
  return name && name !== item.value ? `${item.value} — ${name}` : item.value;
}

export function localeChoices(current = "") {
  const preferred = PREFERRED.flatMap((value) => STALWART_LOCALES.filter((item) => item.value === value));
  const rest = STALWART_LOCALES.filter((item) => !PREFERRED.includes(item.value)).sort((a, b) => a.value.localeCompare(b.value));
  const options = [...preferred, ...rest];
  if (current && !options.some((item) => item.value === current)) options.unshift({ value: current, label: current });
  return options;
}
